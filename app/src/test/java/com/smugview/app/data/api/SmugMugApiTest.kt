        private fun getShortSummary(testName: String, actual: String): String {
            if (actual.contains("Error:")) return "Error"
            return when (testName) {
                "testUnlockActions", "unlockNode / unlockAlbum" -> {
                    "HTTP 200/200 Success"
                }
                "testPagingAlbumImages", "testPagingSearchImages" -> {
                    val match = Regex("Page 1 size: (\\d+), Page 2 size: (\\d+)").find(actual)
                    if (match != null) {
                        "Page 1: ${match.groupValues[1]}, Page 2: ${match.groupValues[2]}"
                    } else "Success"
                }
                else -> {
                    val clean = actual.removePrefix("Fetched ").removePrefix("Image details fetched, ")
                    if (clean.length > 35) clean.take(32) + "..." else clean
                }
            }
        }

