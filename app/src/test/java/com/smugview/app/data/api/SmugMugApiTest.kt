    private fun setupApi(): Pair<SmugMugApi, String> {
        val apiKey = if (RECORD_MODE) {
            val properties = Properties()
            val file = File("c:/src/kidzi/GitHub/SmugView/local.properties")
            assertTrue("local.properties file must exist at " + file.absolutePath, file.exists())
            file.inputStream().use { properties.load(it) }
            val key = properties.getProperty("smugmug.api.key") ?: ""
            assertFalse("smugmug.api.key must not be empty", key.isEmpty())
            key
        } else {
            "dummyApiKey"
        }

        val logging = HttpLoggingInterceptor().apply {
            level = HttpLoggingInterceptor.Level.BODY
        }
        val retryInterceptor = okhttp3.Interceptor { chain ->
            var request = chain.request()
            var response = chain.proceed(request)
            var tryCount = 0
            val maxLimit = 5
            var delayMs = 500L

            while (!response.isSuccessful && (response.code == 429 || response.code in 500..599) && tryCount < maxLimit) {
                tryCount++
                
                var sleepTimeMs = delayMs
                if (response.code == 429) {
                    val retryAfterHeader = response.header("Retry-After") ?: response.header("retry-after")
                    val retryAfterSeconds = retryAfterHeader?.toLongOrNull()
                    if (retryAfterSeconds != null) {
                        sleepTimeMs = retryAfterSeconds * 1000L
                    }
                }

                response.close()
                try {
                    Thread.sleep(sleepTimeMs)
                } catch (e: InterruptedException) {
                    Thread.currentThread().interrupt()
                    throw java.io.IOException(e)
                }
                delayMs *= 2
                response = chain.proceed(request)
            }
            response
        }

        val cookieJar = object : okhttp3.CookieJar {
            private val cookieStore = HashMap<String, MutableMap<String, okhttp3.Cookie>>()

            override fun saveFromResponse(url: okhttp3.HttpUrl, cookies: List<okhttp3.Cookie>) {
                val hostCookies = cookieStore.getOrPut(url.host) { HashMap() }
                for (cookie in cookies) {
                    hostCookies[cookie.name] = cookie
                }
            }

            override fun loadForRequest(url: okhttp3.HttpUrl): List<okhttp3.Cookie> {
                val hostCookies = cookieStore[url.host] ?: return emptyList()
                val now = System.currentTimeMillis()
                return hostCookies.values.filter { it.expiresAt > now }
            }
        }

        val okHttpClientBuilder = OkHttpClient.Builder()
            .cookieJar(cookieJar)
            .addInterceptor { chain ->
                val request = chain.request().newBuilder()
                    .header("Accept", "application/json")
                    .header("User-Agent", "SmugView-Android-App/1.0")
                    .build()
                chain.proceed(request)
            }

        if (RECORD_MODE) {
            okHttpClientBuilder.addInterceptor(SavingInterceptor())
            okHttpClientBuilder.addInterceptor(retryInterceptor)
            okHttpClientBuilder.addInterceptor(logging)
        } else {
            okHttpClientBuilder.addInterceptor(PlaybackInterceptor())
        }

        val okHttpClient = okHttpClientBuilder.build()

        val retrofit = Retrofit.Builder()
            .baseUrl("https://api.smugmug.com/api/v2/")
            .client(okHttpClient)
            .addConverterFactory(GsonConverterFactory.create())
            .build()

        return Pair(retrofit.create(SmugMugApi::class.java), apiKey)
    }

