        private fun getFilename(url: okhttp3.HttpUrl): String {
            val pathSegment = url.encodedPath.removePrefix("/api/v2/").replace("/", "_").replace("!", "_")
            val sb = java.lang.StringBuilder(pathSegment)
            
            url.queryParameter("Text")?.let { sb.append("_Text_").append(it) }
            url.queryParameter("Keywords")?.let { sb.append("_Keywords_").append(it) }
            url.queryParameter("start")?.let { sb.append("_start_").append(it) }
            url.queryParameter("count")?.let { sb.append("_count_").append(it) }
            url.queryParameter("_expand")?.let { sb.append("_expand_").append(it) }
            
            sb.append(".json")
            return sb.toString().replace(Regex("[^a-zA-Z0-9_.-]"), "_")
        }
    }

    class PlaybackInterceptor : okhttp3.Interceptor {
        override fun intercept(chain: okhttp3.Interceptor.Chain): okhttp3.Response {
            val url = chain.request().url
            val filename = getFilename(url)
            val file = File(snapshotsDir, filename)
            if (!file.exists()) {
                throw FileNotFoundException("Snapshot file not found: ${file.absolutePath} for URL: $url")
            }
            val json = file.readText()
            return okhttp3.Response.Builder()
                .request(chain.request())
                .protocol(okhttp3.Protocol.HTTP_1_1)
                .code(200)
                .message("OK")
                .body(json.toResponseBody("application/json".toMediaTypeOrNull()))
                .build()
        }
    }

    class SavingInterceptor : okhttp3.Interceptor {
        override fun intercept(chain: okhttp3.Interceptor.Chain): okhttp3.Response {
            val response = chain.proceed(chain.request())
            val url = chain.request().url
            val filename = getFilename(url)
            val responseBody = response.body
            val json = responseBody?.string() ?: ""
            if (!snapshotsDir.exists()) {
                snapshotsDir.mkdirs()
            }
            val file = File(snapshotsDir, filename)
            file.writeText(json)
            return response.newBuilder()
                .body(json.toResponseBody(responseBody?.contentType()))
                .build()
        }
    }

